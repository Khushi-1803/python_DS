import math

# Sample numbers
a = 10
b = 3
numbers = [4, 7, 1, 9, 2]

# Min and Max
print("Minimum value:", min(numbers))
print("Maximum value:", max(numbers))

# Power
print("Power (a^b):", pow(a, b))   # 10^3

# Square Root
print("Square root of a:", math.sqrt(a))

# Ceil and Floor
x = 4.3
print("Ceil of", x, ":", math.ceil(x))
print("Floor of", x, ":", math.floor(x))